"""Exports simulasi_asn_rev.xlsx to the web prototype (app/src/features/asnSim/simData.ts), so the page ASN Simulation shows the same data."""
import datetime as dt, json, os, sys
import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'simulasi_asn_rev.xlsx')
OUT = os.path.join(HERE, '..', '..', 'app', 'src', 'features', 'asnSim', 'simData.ts')
FILL = {'FFFFFF00': 'y', 'FFF4B084': 'r'}


def val(v):
    if isinstance(v, dt.datetime):
        return v.strftime('%Y-%m-%d')
    return '' if v is None else str(v)


def mark(c):
    return FILL.get(str(c.fill.fgColor.rgb)) if c.fill and c.fill.fill_type else None


def table(ws, hr, c0, extra=()):
    """Header at row hr from column c0 to the first empty header (+ extra columns); data rows until column c0 is empty."""
    cols = []
    while ws.cell(hr, c0 + len(cols)).value is not None:
        cols.append(c0 + len(cols))
    cols += [c for c in extra if c not in cols]
    rows, r = [], hr + 1
    while ws.cell(r, c0).value is not None:
        cells = [ws.cell(r, c) for c in cols]
        rows.append({'cells': [val(c.value) for c in cells], 'mark': [mark(c) for c in cells]})
        r += 1
    return {'headers': [val(ws.cell(hr, c).value) for c in cols], 'rows': rows}


wb = openpyxl.load_workbook(SRC)
s1, s2, st = wb['Sheet1'], wb['Sheet2'], wb['#TEMP_INSTRUCTION']
days = {}
for r in range(1, s1.max_row + 1):
    name = s1.cell(r, 1).value
    if name in ('TB_R_H0253_ORDER_CONTROL_PRE', 'NSP.TB_R_H0253_ORDER_CONTROL_PRE'):
        t = table(s1, r + 1, 1, extra=(13,))
        date = val(s1.cell(r - 1, 1).value)
        days.setdefault(date, []).append({'title': val(s1.cell(r - 2, 1).value), 'table': name, 'kind': 'rep' if name.startswith('NSP') else 'gsys', **t})
ref = []
for c0 in (2, 12):
    for r in range(1, s2.max_row + 1):
        v = s2.cell(r, c0).value
        if isinstance(v, str) and (v.startswith('TB_') or v.startswith('Cek PO')) and s2.cell(r + 1, c0).value is not None:
            ref.append({'title': v, **table(s2, r + 1, c0), 'row': r})
ref.sort(key=lambda t: (t['row'], t['title']))
searches, notes = [], []
for r in range(1, st.max_row + 1):
    v = st.cell(r, 1).value
    if isinstance(v, str) and st.cell(r + 1, 1).value == 'SORT_SEQ':
        searches.append({'title': v, 'date': v[:10], **table(st, r + 1, 1)})
    elif isinstance(v, str) and r > 1 and st.cell(r, 1).font.i and not v.startswith('Teks biru'):
        notes.append(v)
data = {'intro': val(st.cell(1, 1).value), 'days': [{'date': d, 'blocks': b} for d, b in days.items()], 'searches': searches,
        'ref': [{k: t[k] for k in ('title', 'headers', 'rows')} for t in ref], 'notes': notes}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by deliverables/simulasi_asn/export_web.py from simulasi_asn_rev.xlsx — do not edit by hand. */\n')
    f.write("import type { SimData } from './types';\n\n")
    f.write('export const SIM: SimData = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
print('written', OUT, len(days), 'days', len(searches), 'searches', len(ref), 'tables', len(notes), 'notes')
