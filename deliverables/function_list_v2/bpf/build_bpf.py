"""Build the Business Process Flow level 2.

  python3 build_bpf.py ts     -> app/src/features/bpf/bpfData.ts (data of the prototype page Business Process Flow)
  node bpf_shots.mjs URL DIR  -> one diagram PNG per flow, taken from the prototype page (document names)
  python3 build_bpf.py xlsx   -> Crossdock_BPF_Level2.xlsx (diagram + step table per flow, abnormality list)
Run from this folder; build_bpf.sh does all three."""
import json, os, sys
from bpf_data import ABNORMALITY, FLOWS, LANES
from bpf_shapes import drawio, excel_drawing

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
TS_OUT = os.path.join(ROOT, 'app', 'src', 'features', 'bpf', 'bpfData.ts')
XLSX_OUT = os.path.join(HERE, 'Crossdock_BPF_Level2.xlsx')
SHOTS = os.path.join(HERE, 'shots')
DRAWIO_OUT = os.path.join(HERE, 'Crossdock_BPF_Level2.drawio')
DIAGRAM_Y = 32 + 20 + 20 + 4  # rows 1-3 (24 pt + 15 pt + 15 pt) and a small margin
AB_KEYS = ['id', 'flow', 'step', 'fn', 'condition', 'detection', 'system', 'pic', 'action']


def check():
    abs_ = {a[0] for a in ABNORMALITY}
    for f in FLOWS:
        ids = {s['id'] for s in f['steps']}
        bands = {b[0]: b[2] for b in f['bands']}
        for s in f['steps']:
            assert s['lane'] in f['lanes'], s['id']
            assert s['slot'] < bands[s['band']], s['id']
            assert set(s['next']) <= ids, s['id']
            assert set(s['ab']) <= abs_, s['id']


def ts():
    data = {
        'lanes': LANES,
        'flows': [dict(f, bands=[{'id': b[0], 'label': b[1], 'slots': b[2]} for b in f['bands']]) for f in FLOWS],
        'abnormality': [dict(zip(AB_KEYS, a)) for a in ABNORMALITY],
    }
    os.makedirs(os.path.dirname(TS_OUT), exist_ok=True)
    with open(TS_OUT, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by deliverables/function_list_v2/bpf/build_bpf.py from bpf_data.py. Do not edit by hand. */\n'
                 'import type { BpfData } from \'./types\';\n\n'
                 f'export const BPF: BpfData = {json.dumps(data, ensure_ascii=False, indent=1)};\n')
    print('written', TS_OUT)


def xlsx():
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    thin = Side(style='thin', color='FF808080')
    box = Border(left=thin, right=thin, top=thin, bottom=thin)
    head = PatternFill('solid', fgColor='FF1F3864')
    f_head = Font(name='Arial', size=9, bold=True, color='FFFFFFFF')
    f_body, f_bold = Font(name='Arial', size=9), Font(name='Arial', size=9, bold=True)
    f_title, f_sub = Font(name='Arial', size=14, bold=True, color='FF1F3864'), Font(name='Arial', size=9, color='FF595959')
    lane_fill = {'GT': 'FFEDEDED', 'NB': 'FFDBE5F4', 'PR': 'FFE3F1DF', 'DS': 'FFFDE4D4', 'SP': 'FFFFF2CC', 'AP': 'FFECE4F5'}
    wrap = Alignment(wrap_text=True, vertical='top')

    def table(ws, r, cols, widths, rows, fills=None):
        for c, (t, w) in enumerate(zip(cols, widths), 1):
            cell = ws.cell(r, c, t)
            cell.font, cell.fill, cell.border = f_head, head, box
            cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
            ws.column_dimensions[cell.column_letter].width = max(ws.column_dimensions[cell.column_letter].width or 0, w)
        for i, row in enumerate(rows):
            r += 1
            for c, v in enumerate(row, 1):
                cell = ws.cell(r, c, v)
                cell.font, cell.border, cell.alignment = (f_bold if c == 1 else f_body), box, wrap
                if fills and fills[i] and c <= 3:
                    cell.fill = PatternFill('solid', fgColor=fills[i])
            longest = max(len(str(v)) / max(widths[c] * 1.1, 1) for c, v in enumerate(row))
            ws.row_dimensions[r].height = max(15, 12 * (int(longest) + 1 + max(str(v).count('\n') for v in row)))
        return r

    wb = Workbook()
    drawings = {}
    ws = wb.active
    ws.title = 'Cover'
    ws.sheet_view.showGridLines = False
    ws['A2'] = 'Crossdock Optimization – Business Process Flow Level 2'
    ws['A2'].font = f_title
    ws['A3'] = 'X axis = PIC (swimlane), Y axis = timeline. Detail down to table level, with the abnormality conditions. Function IDs follow function list v2 (XD01–XD15).'
    ws['A3'].font = f_sub
    r = table(ws, 5, ['Item', 'Value'], [22, 110], [
        ['Document', 'Business Process Flow Level 2 (Crossdock)'], ['Project', 'Crossdock Optimization (NSP)'],
        ['Author', 'FID Rayhan'], ['Revision', '0.1 Initial Draft (19-Oct-2026)'],
        ['Source', 'UISS XD01–XD15 (deliverables/function_list_v2), decisions of 18-Oct and 19-Oct'],
        ['Prototype', 'Menu Common → Business Process Flow (https://ivanrayhannn.github.io/crossdockpoc/#/bpf)']])
    r = table(ws, r + 2, ['Sheet', 'Content'], [22, 110],
              [[f['id'], f"{f['title']}: {f['desc']}"] for f in FLOWS] + [['Abnormality', 'All abnormality conditions (AB01–AB16): detection, system handling, PIC and action.']])
    table(ws, r + 2, ['Lane (PIC)', 'Role in the flow'], [22, 110], [
        [LANES['GT'], 'Source system of customer orders (H0253), destination master (H0125) and actual demand; receives the crossdock master.'],
        [LANES['NB'], 'Scheduled and on-demand batches / screen back-end of NSP (XD04–XD13, Create / Submit ASN).'],
        [LANES['PR'], 'Part List tab of XD01: candidate parts, Min MAD, Pcs/Case, Max Case/Day; [Run calculation (Part List)].'],
        [LANES['DS'], 'Mapping per Destination tab of XD01, [Sync]; destination detail and Hold in XD10; Log Monitoring; CONFLICT handling.'],
        [LANES['SP'], 'ASN Crossdock Creation (XD10) and ASN Inquiry (XD15).'],
        [LANES['AP'], 'Receives the crossdock master file by SFTP (Option #3).']],
        fills=[lane_fill[k] for k in ['GT', 'NB', 'PR', 'DS', 'SP', 'AP']])

    for f in FLOWS:
        ws = wb.create_sheet(f['id'])
        ws.sheet_view.showGridLines = False
        ws['A1'] = f"{f['id']} {f['title']}"
        ws['A1'].font = f_title
        ws['A2'] = f['desc'] + ' X = PIC, Y = timeline. Red tags = abnormality (sheet Abnormality). All shapes are editable (also in Crossdock_BPF_Level2.drawio).'
        ws['A2'].font = f_sub
        # rows 1-3 and the rows under the diagram get a fixed height (15 pt = 20 px), so the shapes sit at a known place
        ws.row_dimensions[1].height, ws.row_dimensions[2].height, ws.row_dimensions[3].height = 24, 15, 15
        dxml, dh = excel_drawing(f, LANES, DIAGRAM_Y)
        n = int(dh / 20) + 3
        for i in range(4, 4 + n):
            ws.row_dimensions[i].height = 15
        top = 4 + n
        drawings[ws.title] = dxml
        band = {b[0]: b[1] for b in f['bands']}
        order = {b[0]: i for i, b in enumerate(f['bands'])}
        steps = sorted(f['steps'], key=lambda s: (order[s['band']], s['slot'], f['lanes'].index(s['lane'])))
        ws.cell(top, 1, 'Step detail').font = f_bold
        table(ws, top + 1, ['Step', 'Timeline', 'PIC', 'Function', 'Activity', 'Read (table)', 'Write (table)', 'Next', 'Abnormality'],
              [7, 22, 18, 12, 40, 36, 40, 10, 12],
              [[s['id'], band[s['band']], LANES[s['lane']], s['fn'] or '-', s['title'], '\n'.join(s['read']) or '-', '\n'.join(s['write']) or '-',
                ', '.join(s['next']) or 'End', ', '.join(s['ab']) or '-'] for s in steps],
              fills=[lane_fill[s['lane']] for s in steps])
        ws.page_setup.orientation = 'landscape'
        ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
        ws.sheet_properties.pageSetUpPr.fitToPage = True

    ws = wb.create_sheet('Abnormality')
    ws.sheet_view.showGridLines = False
    ws['A1'] = 'Abnormality conditions'
    ws['A1'].font = f_title
    ws['A2'] = 'Per condition: where it happens (flow / step / function), how it is detected, what the system does and what the PIC does.'
    ws['A2'].font = f_sub
    table(ws, 4, ['ID', 'Flow', 'Step', 'Function', 'Condition', 'Detection', 'System handling', 'PIC', 'PIC action'],
          [7, 8, 10, 12, 40, 24, 44, 18, 44], [list(a) for a in ABNORMALITY])
    ws.page_setup.orientation = 'landscape'
    ws.page_setup.fitToWidth, ws.page_setup.fitToHeight = 1, 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    wb.save(XLSX_OUT)
    add_drawings(XLSX_OUT, [ws.title for ws in wb.worksheets], drawings)
    print('written', XLSX_OUT)
    with open(DRAWIO_OUT, 'w', encoding='utf-8') as fh:
        fh.write(drawio(FLOWS, LANES))
    print('written', DRAWIO_OUT)


def add_drawings(path, titles, drawings):
    """openpyxl cannot write shapes: add one DrawingML part per flow sheet to the saved workbook."""
    import re, shutil, tempfile, zipfile
    tmp = tempfile.mktemp(suffix='.xlsx')
    shutil.copy(path, tmp)
    with zipfile.ZipFile(tmp) as zin, zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as zout:
        files = {i.filename: zin.read(i.filename) for i in zin.infolist()}
        ct = files['[Content_Types].xml'].decode()
        for k, title in enumerate(titles, 1):
            if title not in drawings:
                continue
            sheet, rels = f'xl/worksheets/sheet{k}.xml', f'xl/worksheets/_rels/sheet{k}.xml.rels'
            assert sheet in files and rels not in files, sheet
            dn = f'xl/drawings/drawing{k}.xml'
            files[dn] = drawings[title].encode()
            files[rels] = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                           f'<Relationship Id="rIdBpf1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/drawing" Target="../drawings/drawing{k}.xml"/>'
                           '</Relationships>').encode()
            x = files[sheet].decode()
            if 'xmlns:r=' not in x[:x.index('>', x.index('<worksheet'))]:
                x = x.replace('<worksheet ', '<worksheet xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" ', 1)
            x = re.sub(r'(<tableParts|<extLst|</worksheet>)', '<drawing r:id="rIdBpf1"/>\\1', x, count=1)
            files[sheet] = x.encode()
            ct = ct.replace('</Types>', f'<Override PartName="/{dn}" ContentType="application/vnd.openxmlformats-officedocument.drawing+xml"/></Types>')
        files['[Content_Types].xml'] = ct.encode()
        for name, data in files.items():
            zout.writestr(name, data)
    os.remove(tmp)


if __name__ == '__main__':
    check()
    {'ts': ts, 'xlsx': xlsx}[sys.argv[1]]()
