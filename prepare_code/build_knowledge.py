"""One Markdown file to upload as Project knowledge (Claude Projects or another AI assistant): the sync of the Crossdock Master to
GTOPAS and AP POLE, from the staging tables to the robots.
Sources (all generated, regenerate them first): tables.md, rpa/XD06_*.md, rpa/XD07_*.md, uiss/XD06_*.md, uiss/XD07_*.md,
sql/crossdock_staging_sync.sql. Pictures are left out (a knowledge file is read as text): each picture becomes one line saying what it shows.
Output: knowledge/Crossdock_Sync_RPA_Knowledge.md. Run: python3 prepare_code/build_knowledge.py (from the repository root)."""
import datetime
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'knowledge', 'Crossdock_Sync_RPA_Knowledge.md')
read = lambda p: open(os.path.join(HERE, p), encoding='utf-8').read()
one = lambda pat: read(os.path.relpath(glob.glob(os.path.join(HERE, pat))[0], HERE))


def demote(md, by):
    """Move every heading down by `by` levels and drop the generated-file line, so the parts sit under one title."""
    md = re.sub(r'^_Generated by .*_\n\n?', '', md, flags=re.M)
    return re.sub(r'^(#{1,6}) ', lambda m: '#' * min(6, len(m.group(1)) + by) + ' ', md, flags=re.M)


def no_pictures(md):
    """A picture is replaced by one line, so the text still says which screen the step shows."""
    md = re.sub(r'!\[(.*)\]\(([^)\s]+)\)', lambda m: f'_[Screen: {m.group(1)}; picture {os.path.basename(m.group(2))} not included]_', md)
    return md


def table_section(md, name):
    m = re.search(rf'^#### {name} \(.*?(?=^#### |\Z)', md, flags=re.M | re.S)
    return m.group(0).rstrip() + '\n'


tables = read('tables.md')
parts = [
    '# Crossdock Master sync to GTOPAS and AP POLE: knowledge file', '',
    f'_Generated {datetime.date.today():%d-%b-%Y} by prepare_code/build_knowledge.py from the UISS, the RPA step documents and the staging SQL of the '
    'Crossdock project (NSP). Example data are dummy parts DUMMY-00x and dummy destinations. Pictures are not included._', '',
    '## Contents', '',
    '1. Summary of the rules',
    '2. Staging tables',
    '3. RPA steps XD06 (GTOPAS)',
    '4. RPA steps XD07 (AP POLE)',
    '5. UISS XD06 IF Cross Dock Master to GTOPAS',
    '6. UISS XD07 IF Cross Dock Master to AP POLE',
    '7. SQL: tables, stored procedures, views, queries', '',
    '## 1. Summary of the rules', '',
    '- NSP screens and uploads (XD01 Kanban / Export Crossdock Master, XD02, XD03) and the batch XD05 update the master, then call '
    '**SP_STG_WRITE**, which writes the change to a staging table in the format of the target: TB_H_STG_APPOLE_KANBAN (AP POLE file '
    'LLM9Q910), TB_H_STG_APPOLE_EXPORT (AP POLE file LLM9Q880), TB_H_STG_GTOPAS (GTOPAS screen WVJA5204).',
    '- **SYNC_STATUS** is 0 (to send) or 1 (sent). A key has at most one row with 0. Keys: Kanban PERIOD + PART_NO; Export PERIOD + '
    'NSP_PART_NO + DEST_CODE + ORDER_TYPE; GTOPAS PERIOD + P_NO + DESTINATION_CODE.',
    '- A new change of a key updates its unsent row (example: Case/Day 5 -> 4 -> 6 before [Sync] leaves one row with 6). A change back to '
    'the value already sent deletes the unsent row (nothing to send). A sent row (1) is never changed; the next change inserts a new row.',
    '- Kanban OPERATION_TYPE (set at the save, against the last Max sent): 1 Max down, 2 Max up, 3 Max same, 4 never sent, 5 only the '
    'destinations changed (header row, ACTION KEEP, not uploaded). The header 5 is deleted when no Export row of the part waits.',
    '- **[Sync]** (D/S, Export Crossdock Master) calls **SP_STG_SYNC**: rows 0 -> 1 with **SYNC_DT** = time of the click, the same value '
    'for the whole run (AP POLE: Current and Next period; GTOPAS: Current only). NSP passes SYNC_DT to the RPA parent flow. There is no run ID column.',
    '- RPA parent flow CDX_SYNC_PARENT: GTOPAS rows in the run -> scenario 1, XD06 first, XD07 only when XD06 succeeded; no GTOPAS row -> '
    'scenario 2, XD07 only. Period Rollover (day 1, 00:10, **SP_STG_ROLLOVER**): GTOPAS rows of the new Current period, XD06 only.',
    "- Robots use a read-only DB user and read `WHERE SYNC_STATUS = '1' AND SYNC_DT = :sync_dt`. Nothing is written back to NSP; the result is an e-mail. "
    '[Re-send last Sync] runs MAX(SYNC_DT) again.',
    '- XD07 uploads up to three files in this order: 1 EXPORT_PRE (Export rows of parts whose Max goes down), 2 KANBAN (OPERATION_TYPE 1 to 4), '
    '3 EXPORT_POST (other Export rows). Inside a file, per part, down / delete (0) rows come before up / add rows. A file without rows is not made.',
    '', '## 2. Staging tables', '',
    'Columns of the three staging tables. The views V_APPOLE_UPLOAD_KANBAN / V_APPOLE_UPLOAD_EXPORT are in section 7.', '',
    demote(table_section(tables, 'TB_H_STG_APPOLE_KANBAN'), -1),
    demote(table_section(tables, 'TB_H_STG_APPOLE_EXPORT'), -1),
    demote(table_section(tables, 'TB_H_STG_GTOPAS'), -1),
    '## 3. RPA steps XD06 (GTOPAS)', '', no_pictures(demote(one('rpa/XD06_*.md'), 2)),
    '## 4. RPA steps XD07 (AP POLE)', '', no_pictures(demote(one('rpa/XD07_*.md'), 2)),
    '## 5. UISS XD06 IF Cross Dock Master to GTOPAS', '', no_pictures(demote(one('uiss/XD06_*.md'), 2)),
    '## 6. UISS XD07 IF Cross Dock Master to AP POLE', '', no_pictures(demote(one('uiss/XD07_*.md'), 2)),
    '## 7. SQL: tables, stored procedures, views, queries', '',
    'File prepare_code/sql/crossdock_staging_sync.sql (SQL Server). Checked with a parser only, not yet run on a database.', '',
    '```sql', read('sql/crossdock_staging_sync.sql').rstrip(), '```', '',
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
text = '\n'.join(parts)
text = re.sub(r'\n{3,}', '\n\n', text)
open(OUT, 'w', encoding='utf-8').write(text)
print('saved', os.path.relpath(OUT, os.path.dirname(HERE)), len(text), 'chars')
